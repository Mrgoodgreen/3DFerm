const dicts: Record<string, Dict> = { ru, en, tr };
let current: Dict = ru;
let currentLang = 'ru';

const RU_LIKE = ['ru', 'be', 'kk', 'uk', 'uz', 'hy', 'az', 'ka', 'ky', 'tg', 'tk'];

export function setLang(lang: string) {
  const l = (lang || 'ru').toLowerCase().slice(0, 2);
  if (dicts[l]) currentLang = l;
  else if (RU_LIKE.includes(l)) currentLang = 'ru';
  else currentLang = 'en';
  current = dicts[currentLang];
  document.documentElement.lang = currentLang;
}

export function getLang() {
  return currentLang;
}

export function t(key: string, params?: Record<string, string | number>): string {
  let s = current[key] ?? en[key] ?? key;
  if (params) for (const k in params) s = s.split(`{${k}}`).join(String(params[k]));
  return s;
}

export function fmt(n: number): string {
  n = Math.floor(n);
  if (n < 10000) return String(n);
  if (n < 1e6) return (n / 1e3).toFixed(n < 1e5 ? 1 : 0).replace(/\.0$/, '') + 'K';
  if (n < 1e9) return (n / 1e6).toFixed(n < 1e8 ? 1 : 0).replace(/\.0$/, '') + 'M';
  return (n / 1e9).toFixed(1).replace(/\.0$/, '') + 'B';
}
